# Receptor-state integration has a much higher per-interval cost than the
# legacy two-state model. Bound an entire drug sweep, not just each cell.
_DRUG_SWEEP_WORK_LIMIT = 3_000_000
_DRUG_SWEEP_BUDGET_MESSAGE = (
    "This receptor-state sweep exceeds the aggregate computation budget. "
    "Use fewer axis values or a shorter simulation; a shorter simulation also "
    "leaves room for a finer timestep. The timestep will not be changed automatically."
)


def get_presets() -> list[dict[str, Any]]:
    """Return independent, reproducible parameter documents for classroom use.

    These scenarios are not experimentally calibrated conditions or treatments.
    Every result is generated by the same equations used for manual experiments.
    """
    baseline = SimulationParameters.spatial_defaults()
    cases = [
        ("baseline", "Baseline neurotransmission",
         "Illustrative simultaneous glutamate and GABA release with default receptor availability.",
         baseline),
        ("excitation", "Excitation-dominant input",
         "Illustrative isolated glutamate input: GABA release is zero; all membrane settings are unchanged.",
         replace(baseline, gaba=replace(baseline.gaba, release_dose_uM_um=0))),
        ("inhibition", "Inhibition-dominant input",
         "Illustrative release imbalance: glutamate dose is 500 and GABA dose is 1200 µM·µm per event; receptor availability is unchanged.",
         replace(baseline, glutamate=replace(baseline.glutamate, release_dose_uM_um=500),
                 gaba=replace(baseline.gaba, release_dose_uM_um=1200))),
        ("reduced_clearance", "Reduced glutamate clearance",
         "Illustrative slower removal: glutamate clearance falls from 0.20 to 0.04 ms⁻¹, prolonging extracellular exposure in the effective domain.",
         replace(baseline, glutamate=replace(baseline.glutamate, clearance_per_ms=0.04))),
        ("increased_gabaa", "More functional GABA-A receptors",
         "Illustrative receptor change: GABA-A availability is 3× baseline. Transmitter release and occupancy kinetics are unchanged.",
         replace(baseline, gaba=replace(baseline.gaba, receptor_availability=3))),
        ("delayed_inhibition", "Delayed GABA release",
         "Illustrative timing change: GABA arrives at 18 ms, eight milliseconds after glutamate, allowing excitation to develop first.",
         replace(baseline, gaba=replace(baseline.gaba, release_times_ms=(18.0,)))),
        ("subthreshold", "Subthreshold excitation",
         "Illustrative weak glutamate input: 50 µM·µm per event with no GABA release; receptor activation remains insufficient to reach threshold.",
         replace(baseline, glutamate=replace(baseline.glutamate, release_dose_uM_um=50),
                 gaba=replace(baseline.gaba, release_dose_uM_um=0))),
        ("zero_input", "Zero synaptic input",
         "Illustrative control: both release doses are zero, leaving the neuron at its resting potential.",
         replace(baseline, glutamate=replace(baseline.glutamate, release_dose_uM_um=0),
                 gaba=replace(baseline.gaba, release_dose_uM_um=0))),
    ]
    return [{"id": identifier, "name": name, "description": description,
             "parameters": parameters.to_dict()}
            for identifier, name, description, parameters in cases]


def _axis(values: list[float], name: str, maximum: float) -> list[float]:
    if not isinstance(values, (list, tuple)) or not 2 <= len(values) <= 7:
        raise ValueError(f"{name} must contain 2 to 7 values.")
    for value in values:
        if isinstance(value, bool) or not isinstance(value, (int, float)) or not math.isfinite(value):
            raise ValueError(f"{name} values must be finite numbers.")
        if not 0 <= value <= maximum:
            raise ValueError(f"{name} values must be between 0 and {maximum:g}.")
    numbers = [float(value) for value in values]
    if any(right <= left for left, right in zip(numbers, numbers[1:])):
        raise ValueError(f"{name} must be strictly increasing with no duplicate values.")
    return numbers


def run_sweep(parameters: SimulationParameters,
              glutamate_doses_uM_um: list[float],
              gaba_availabilities: list[float]) -> dict[str, Any]:
    """Vary dose (columns) and GABA-A availability (rows), preserving accuracy.

    Transmitter transport does not depend on receptor availability in this model.
    Therefore each dose's computed local concentration traces can be reused across
    availability values. All receptor/membrane integrations retain the supplied
    timestep, release-aligned timeline, kinetics, threshold and reset behavior.
    No coarse surrogate, interpolation, randomness or firing probability is used.
    """
    if not isinstance(parameters, SimulationParameters):
        raise ValueError("A validated SimulationParameters object is required for the sweep.")
    parameters.validate()
    doses = _axis(glutamate_doses_uM_um, "Glutamate dose axis (µM·µm)", 100000)
    availabilities = _axis(gaba_availabilities, "GABA-A availability axis (relative)", 100)
    width, height = len(doses), len(availabilities)
    cell_count = width * height
    if cell_count > 49:
        raise ValueError("A sweep supports at most 49 parameter combinations.")
    estimated_intervals = math.ceil(parameters.duration_ms / parameters.dt_ms) + 1 + len(parameters.glutamate.release_times_ms) + len(parameters.gaba.release_times_ms)
    if estimated_intervals * cell_count > 500000:
        raise ValueError("This sweep exceeds the integration work limit. Use fewer axis values or a shorter simulation; the timestep will not be changed automatically.")
    if parameters.transport is not None and 2 * width * parameters.transport.n_cells * estimated_intervals > 25000000:
        raise ValueError("This sweep exceeds the spatial work limit. Use fewer dose values, fewer spatial cells, or a shorter simulation.")
    if math.ceil(parameters.duration_ms / parameters.membrane.refractory_ms) * cell_count > 2000000:
        raise ValueError("This sweep could generate too many events. Use fewer combinations or a shorter simulation.")
    drug_work = 0.0
    if parameters.pharmacology is not None:
        # The engine's conservative work proxy contains at least 40 units per
        # interval, regardless of concentration. Reject oversized grids before
        # transport or receptor integration; the actual proxy below also accounts
        # for stiffness. Use the release-aligned timeline, including short pieces.
        minimum_drug_work = 40 * (len(simulation_timeline(parameters)) - 1) * cell_count
        if minimum_drug_work > _DRUG_SWEEP_WORK_LIMIT:
            raise ValueError(_DRUG_SWEEP_BUDGET_MESSAGE)

    spike_count: list[list[int]] = [[0] * width for _ in range(height)]
    peak: list[list[float]] = [[0.0] * width for _ in range(height)]
    latency: list[list[float | None]] = [[None] * width for _ in range(height)]
    flagged_cells = []
    warnings_by_code = {}
    recommended_dt_ms = parameters.dt_ms
    for column, dose in enumerate(doses):
        dose_parameters = replace(parameters, glutamate=replace(parameters.glutamate, release_dose_uM_um=dose))
        if parameters.pharmacology is not None:
            # Every costly receptor integration should supply a requested cell,
            # including when the original availability is absent from the axis.
            dose_parameters = replace(dose_parameters,
                gaba=replace(dose_parameters.gaba, receptor_availability=availabilities[0]))
        # This is an ordinary single-run calculation, not a second transport model.
        dose_result = simulate(dose_parameters)
        if parameters.pharmacology is not None:
            # Concentrations and receptor-state kinetics are identical for every
            # availability in this column. Reserve the full column before its
            # cached integrations, using the engine's own stiffness-aware proxy.
            # A rejected request may spend one extra single-run probe; that run
            # is itself bounded by the engine's 3M-unit budget.
            drug_work += height * dose_result.pharmacology["estimated_work_units"]
            if drug_work > _DRUG_SWEEP_WORK_LIMIT:
                raise ValueError(_DRUG_SWEEP_BUDGET_MESSAGE)
        for row, availability in enumerate(availabilities):
            cell_parameters = replace(dose_parameters,
                                      gaba=replace(dose_parameters.gaba, receptor_availability=availability))
            if availability == dose_parameters.gaba.receptor_availability:
                result = dose_result
            else:
                result = integrate_signals(cell_parameters, dose_result.time_ms,
                                           dose_result.glutamate_uM, dose_result.gaba_uM)
                # Local concentration can be zero while transmitter remains
                # elsewhere in a spatial domain. Retain the already-computed
                # mass context so cached cells receive the same chemical
                # resolution screens as an independent full simulation.
                result = replace(result,
                    glutamate_mass_uM_um=dose_result.glutamate_mass_uM_um,
                    gaba_mass_uM_um=dose_result.gaba_mass_uM_um)
            summary = result.summary()
            resolution = numerical_resolution(result)
            if resolution["status"] == "review_required":
                flagged_cells.append({"row": row, "column": column})
                recommended_dt_ms = min(recommended_dt_ms, resolution["recommended_dt_ms"])
                for warning in resolution["warnings"]:
                    previous = warnings_by_code.get(warning["code"])
                    if previous is None or warning["observed"] > previous["observed"]:
                        warnings_by_code[warning["code"]] = warning
            spike_count[row][column] = summary["spike_count"]
            peak[row][column] = summary["peak_membrane_mV"]
            latency[row][column] = summary["first_spike_latency_ms"]

    base_configuration = parameters.to_dict()
    axes = {"glutamate_doses_uM_um": doses, "gaba_availabilities": availabilities}
    source = provenance(base_configuration)
    axes_sha256 = canonical_hash(axes)
    sweep_sha256 = canonical_hash({
        "parameter_sha256": source["parameter_sha256"],
        "model_source_sha256": source["model_source_sha256"],
        "axes_sha256": axes_sha256,
    })
    source.update(analysis_type="deterministic_parameter_sweep", axes_sha256=axes_sha256,
                  sweep_sha256=sweep_sha256)
    return {
        "parameters": base_configuration,
        "axes": axes,
        "spike_count": spike_count,
        "peak_membrane_mV": peak,
        "first_spike_latency_ms": latency,
        "numerical_resolution": {
            "status": "review_required" if flagged_cells else "not_flagged",
            "dt_ms": parameters.dt_ms,
            "recommended_dt_ms": recommended_dt_ms,
            "warnings": list(warnings_by_code.values()),
            "flagged_cells": flagged_cells,
            "peak_note": resolution["peak_note"],
            "interpretation": "Screening flags are not an error estimate. Unflagged cells still need refinement near firing boundaries.",
        },
        "provenance": source,
        "axes_sha256": axes_sha256,
        "sweep_id": sweep_sha256[:20],
        "numerical_settings": {
            "duration_ms": parameters.duration_ms,
            "dt_ms": parameters.dt_ms,
            "n_cells": parameters.transport.n_cells if parameters.transport else None,
            "model_mode": base_configuration["model_mode"],
            "parameter_combinations": cell_count,
            "transport_calculations": width,
        },
        "matrix_layout": "Rows: GABA-A relative availability; columns: glutamate dose (µM·µm).",
        "optimization_note": "Computed transmitter traces are reused without alteration across receptor availability values; numerical resolution is unchanged.",
        "interpretation": "Deterministic model outcomes, not firing probabilities. Presets and default parameters are illustrative rather than experimentally calibrated.",
    }
